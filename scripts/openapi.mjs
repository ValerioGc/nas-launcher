// Generates the OpenAPI document of the launcher out of its code and the TypeScript types of the
// interface out of the document. With --check it writes nothing and fails when either file is out
// of date.
//
// pnpm run api:generate
// pnpm run api:check

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';

export const SCHEMA = 'docs/development/openapi.json';
export const TYPES = 'src/types/api.ts';

async function pretty(text, filepath) {
  const options = await resolveConfig(filepath);
  return format(text, { ...options, filepath });
}

/**
 * The TypeScript types of a document formatted as the repository keeps them.
 */
export async function typesOf(document) {
  const banner = `// Generated by scripts/openapi.mjs out of ${SCHEMA}. Do not edit.\n\n`;
  return pretty(banner + astToString(await openapiTS(JSON.parse(document))), TYPES);
}

export async function generate() {
  const document = execFileSync(
    'cargo',
    ['run', '--quiet', '--locked', '--manifest-path', 'backend/Cargo.toml', '--bin', 'openapi'],
    { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
  );
  return {
    [SCHEMA]: await pretty(document, SCHEMA),
    [TYPES]: await typesOf(document),
  };
}

function current(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return '';
  }
}

async function main() {
  const check = process.argv.includes('--check');
  const files = await generate();
  const stale = Object.entries(files).filter(([file, text]) => current(file) !== text);

  if (check) {
    for (const [file] of stale) {
      console.error(`${file} does not match the code: run pnpm run api:generate`);
    }
    process.exit(stale.length ? 1 : 0);
  }
  for (const [file, text] of stale) {
    writeFileSync(file, text);
    console.log(`${file} updated`);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
